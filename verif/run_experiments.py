import json
import os
from dataclasses import asdict, dataclass
from typing import Dict, List

from mesi_model import BusOp, MesiSystem, run_trace, workload_false_sharing, workload_private, workload_producer_consumer


@dataclass
class ExperimentResult:
    name: str
    total_cycles: int
    bus_utilization: float
    l1_hit_rate_core0: float
    l1_hit_rate_core1: float
    bus_counts: Dict[str, int]


def _hit_rate(hits: int, misses: int) -> float:
    total = hits + misses
    return (hits / total) if total else 0.0


def run_one(name: str, trace) -> ExperimentResult:
    sys = MesiSystem()
    run_trace(sys, trace)

    bus_counts = {op.name: sys.bus_counts[op] for op in BusOp}
    return ExperimentResult(
        name=name,
        total_cycles=sys.total_cycles,
        bus_utilization=(sys.bus_busy_cycles / sys.total_cycles) if sys.total_cycles else 0.0,
        l1_hit_rate_core0=_hit_rate(sys.l1_hits[0], sys.l1_misses[0]),
        l1_hit_rate_core1=_hit_rate(sys.l1_hits[1], sys.l1_misses[1]),
        bus_counts=bus_counts,
    )


def write_results(results: List[ExperimentResult], out_dir: str) -> None:
    os.makedirs(out_dir, exist_ok=True)
    plots_dir = os.path.join(out_dir, "plots")
    os.makedirs(plots_dir, exist_ok=True)

    metrics_path = os.path.join(out_dir, "metrics.json")
    with open(metrics_path, "w", encoding="utf-8") as f:
        json.dump([asdict(r) for r in results], f, indent=2)

    md_path = os.path.join(out_dir, "results.md")
    with open(md_path, "w", encoding="utf-8") as f:
        f.write("# MESI Model Results (Python)\n\n")
        f.write("Generated by `verif/run_experiments.py`.\n\n")
        f.write("| Workload | Total Cycles | Bus Utilization | L1 Hit Rate (Core0) | L1 Hit Rate (Core1) |\n")
        f.write("|---|---:|---:|---:|---:|\n")
        for r in results:
            f.write(
                f"| {r.name} | {r.total_cycles} | {r.bus_utilization:.3f} | {r.l1_hit_rate_core0:.3f} | {r.l1_hit_rate_core1:.3f} |\n"
            )

        f.write("\n## Bus Transactions\n\n")
        for r in results:
            f.write(f"### {r.name}\n\n")
            f.write("| Op | Count |\n|---|---:|\n")
            for op_name, count in r.bus_counts.items():
                f.write(f"| {op_name} | {count} |\n")
            f.write("\n")

    try:
        import matplotlib.pyplot as plt  # type: ignore

        # Plot: bus utilization by workload
        names = [r.name for r in results]
        utils = [r.bus_utilization for r in results]
        plt.figure(figsize=(8, 4))
        plt.bar(names, utils)
        plt.ylabel("Bus Utilization")
        plt.title("Bus Utilization by Workload")
        plt.tight_layout()
        plt.savefig(os.path.join(plots_dir, "bus_utilization.png"), dpi=160)
        plt.close()

        # Plot: BUS_RDX counts by workload (dominant in coherence-heavy traces)
        rdx_counts = [r.bus_counts.get("BUS_RDX", 0) for r in results]
        plt.figure(figsize=(8, 4))
        plt.bar(names, rdx_counts)
        plt.ylabel("BUS_RDX Count")
        plt.title("BUS_RDX by Workload")
        plt.tight_layout()
        plt.savefig(os.path.join(plots_dir, "bus_rdx.png"), dpi=160)
        plt.close()
    except Exception as e:
        # Plotting is optional; keep experiments runnable without extra deps.
        with open(os.path.join(out_dir, "plot_error.txt"), "w", encoding="utf-8") as f:
            f.write(str(e) + "\n")


def main() -> None:
    results = [
        run_one("private", workload_private(iters=1000)),
        run_one("producer_consumer", workload_producer_consumer(iters=2000)),
        run_one("false_sharing", workload_false_sharing(iters=2000)),
    ]
    write_results(results, out_dir=os.path.join(os.path.dirname(__file__), "results"))


if __name__ == "__main__":
    main()

